"""Summarize the committed Tomoe online-stroke corpora."""

import argparse
import json
import statistics
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "tomoe"
REPORT = ROOT / "reports" / "dataset-stats.md"

LANGUAGES = {
    "handwriting-zh_CN.xml": "Simplified Chinese (zh_CN)",
    "handwriting-zh_TW.xml": "Traditional Chinese (zh_TW)",
    "handwriting-ja.xml": "Japanese (ja)",
}


def characters(path):
    root = ET.parse(path).getroot()
    if root.tag == "character-collection":
        for group in root.findall("set"):
            yield from group.findall("character")
    else:
        yield from root.findall("character")


def script_of(character):
    code = ord(character[0]) if character else 0
    if 0x3400 <= code <= 0x4DBF or 0x4E00 <= code <= 0x9FFF or 0xF900 <= code <= 0xFAFF:
        return "Han"
    if 0x3040 <= code <= 0x309F:
        return "Hiragana"
    if 0x30A0 <= code <= 0x30FF or 0xFF66 <= code <= 0xFF9D:
        return "Katakana"
    if code < 0x80:
        return "ASCII"
    return "Other"


def summarize(path):
    classes = []
    samples = 0
    strokes = []
    points = []
    scripts = {}
    for node in characters(path):
        label = (node.findtext("utf8") or "").strip()
        if not label:
            continue
        samples += 1
        classes.append(label)
        stroke_nodes = node.findall("./strokes/stroke")
        strokes.append(len(stroke_nodes))
        points.append(sum(len(stroke.findall("point")) for stroke in stroke_nodes))
        script = script_of(label)
        scripts[script] = scripts.get(script, 0) + 1
    unique = len(set(classes))
    return {
        "classes": unique,
        "samples": samples,
        "samples_per_class": samples / unique if unique else 0,
        "strokes": {
            "min": min(strokes) if strokes else 0,
            "median": statistics.median(strokes) if strokes else 0,
            "max": max(strokes) if strokes else 0,
        },
        "points": {
            "median": statistics.median(points) if points else 0,
            "max": max(points) if points else 0,
        },
        "scripts": scripts,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true", help="print JSON only")
    args = parser.parse_args()

    stats = {}
    for filename, language in LANGUAGES.items():
        path = DATA / filename
        if not path.is_file():
            print(f"missing {path}", file=sys.stderr)
            return 1
        stats[language] = summarize(path)

    if args.json:
        print(json.dumps(stats, ensure_ascii=False, indent=2))
        return 0

    lines = [
        "# Tomoe corpus statistics",
        "",
        "Generated by `scripts/dataset-stats.py` from `data/tomoe/`.",
        "",
        "| Language | Classes | Samples | Samples/class | Strokes median | Points median | Script mix |",
        "|---|---:|---:|---:|---:|---:|---|",
    ]
    for language, item in stats.items():
        scripts = ", ".join(f"{name} {count}" for name, count in sorted(item["scripts"].items()))
        lines.append(
            f"| {language} | {item['classes']:,} | {item['samples']:,} | "
            f"{item['samples_per_class']:.2f} | {item['strokes']['median']:g} | "
            f"{item['points']['median']:g} | {scripts} |"
        )
    lines += [
        "",
        "## Interpretation",
        "",
        "- Simplified and Traditional Chinese have one sample per class. A",
        "  within-class holdout is impossible without an external test set.",
        "- Japanese has a few characters with multiple samples; those can form a",
        "  small within-corpus sanity check, not a full benchmark.",
        "- Synthetic stroke sources (Make Me a Hanzi, AnimCJK) add character",
        "  coverage but not real writer diversity.",
        "",
    ]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {REPORT}")
    print("\n".join(lines[6:]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
